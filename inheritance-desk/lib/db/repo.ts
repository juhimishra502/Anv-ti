export async function createCaseForUser(userId: string, title: string): Promise<CaseRow> {
  const now = nowIso();
  const familyId = newId("fam");
  const caseId = newId("case");
  await sql()`INSERT INTO families (id, name, created_by, created_at) VALUES (${familyId}, ${title}, ${userId}, ${now})`;
  await sql()`
    INSERT INTO family_members (id, family_id, user_id, role, permissions, invited_by, created_at)
    VALUES (${newId("mem")}, ${familyId}, ${userId}, 'coordinator', 'full', NULL, ${now})`;
  const rows = await sql()`
    INSERT INTO cases (id, family_id, created_by, title, status, created_at, updated_at)
    VALUES (${caseId}, ${familyId}, ${userId}, ${title}, 'intake', ${now}, ${now})
    RETURNING *`;
  await sql()`INSERT INTO deceased_persons (id, case_id, updated_at) VALUES (${newId("dec")}, ${caseId}, ${now})`;
  await audit(userId, caseId, "case.created", title);
  return rows[0] as CaseRow;
}

