/** True only if the user is a member of the family that owns the case. */
export async function userCanAccessCase(userId: string, caseId: string): Promise<boolean> {
  const rows = await sql()`
    SELECT 1 FROM cases c
    JOIN family_members fm ON fm.family_id = c.family_id
    WHERE c.id = ${caseId} AND fm.user_id = ${userId} LIMIT 1`;
  return rows.length > 0;
}

export class AccessError extends Error {}

export async function assertCaseAccess(userId: string, caseId: string): Promise<void> {
  if (!(await userCanAccessCase(userId, caseId))) {
    throw new AccessError("Not authorized for this case.");
  }
}

