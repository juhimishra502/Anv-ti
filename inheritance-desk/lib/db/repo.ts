const DECEASED_FIELDS = [
  "full_name",
  "residence_state",
  "residence_district",
  "death_state",
  "death_district",
  "death_date",
  "death_registered",
  "death_certificate",
  "will_status",
  "certificate_copies",
  "will_registered",
  "executor_present",
  "probate_status",
  "dispute_status",
  "applicant_relationship",
  "nri_status",
] as const;

export async function updateDeceased(caseId: string, patch: Partial<Deceased>): Promise<void> {
  const sets: string[] = [];
  const values: unknown[] = [];
  for (const field of DECEASED_FIELDS) {
    if (field in patch) {
      values.push((patch as Record<string, unknown>)[field] ?? null);
      sets.push(`${field} = $${values.length}`);
    }
  }
  if (!sets.length) return;
  values.push(nowIso());
  sets.push(`updated_at = $${values.length}`);
  values.push(caseId);
  await sql().query(
    `UPDATE deceased_persons SET ${sets.join(", ")} WHERE case_id = $${values.length}`,
    values,
  );
  await touchCase(caseId);
}

