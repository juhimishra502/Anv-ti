// ---- Translation cache ------------------------------------------------------

export async function getCachedTranslations(
  locale: string,
  version: string,
  hashes: string[],
): Promise<Map<string, string>> {
  const out = new Map<string, string>();
  if (!hashes.length) return out;
  const rows = (await sql()`
    SELECT source_hash, translated FROM translations
    WHERE locale = ${locale} AND version = ${version} AND source_hash = ANY(${hashes})`) as {
    source_hash: string;
    translated: string;
  }[];
  for (const r of rows) out.set(r.source_hash, r.translated);
  return out;
}

export async function putCachedTranslations(
  locale: string,
  version: string,
  entries: { hash: string; translated: string }[],
): Promise<void> {
  if (!entries.length) return;
  const now = nowIso();
  const q = sql();
  const queries = entries.map(
    (e) => q`
      INSERT INTO translations (id, locale, version, source_hash, translated, created_at)
      VALUES (${`${locale}:${version}:${e.hash}`}, ${locale}, ${version}, ${e.hash}, ${e.translated}, ${now})
      ON CONFLICT (id) DO UPDATE SET translated = excluded.translated, created_at = excluded.created_at`,
  );
  await q.transaction(queries);
}

