export async function addAsset(caseId: string, input: AssetInput): Promise<Asset> {
  const id = newId("ast");
  const now = nowIso();
  const rows = await sql()`
    INSERT INTO assets (id, case_id, asset_type, service, label, institution, institution_id, nominee_status,
      holding_mode, record_type, authority, scheme, details_json, created_at)
    VALUES (${id}, ${caseId}, ${input.asset_type}, ${input.service}, ${input.label ?? null}, ${input.institution ?? null}, ${input.institution_id ?? null}, ${input.nominee_status ?? null}, ${input.holding_mode ?? null}, ${input.record_type ?? null}, ${input.authority ?? null}, ${input.scheme ?? null}, ${input.details_json ?? null}, ${now})
    RETURNING *`;
  if (input.location) {
    const l = input.location;
    await sql()`
      INSERT INTO asset_locations (id, asset_id, state_code, district, municipality,
        tehsil_taluk, village_ward, property_identifier, created_at)
      VALUES (${newId("loc")}, ${id}, ${l.state_code ?? null}, ${l.district ?? null}, ${l.municipality ?? null}, ${l.tehsil_taluk ?? null}, ${l.village_ward ?? null}, ${l.property_identifier ?? null}, ${now})`;
  }
  await touchCase(caseId);
  await audit(null, caseId, "asset.added", `${input.asset_type} (${input.service})`);
  return rows[0] as Asset;
}

export async function listAssets(caseId: string): Promise<(Asset & { location: AssetLocation | null })[]> {
  const assets = (await sql()`SELECT * FROM assets WHERE case_id = ${caseId} ORDER BY created_at`) as Asset[];
  if (assets.length === 0) return [];
  const ids = assets.map((a) => a.id);
  const locs = (await sql()`
    SELECT * FROM asset_locations WHERE asset_id = ANY(${ids}) ORDER BY created_at`) as AssetLocation[];
  const firstByAsset = new Map<string, AssetLocation>();
  for (const l of locs) if (!firstByAsset.has(l.asset_id)) firstByAsset.set(l.asset_id, l);
  return assets.map((a) => ({ ...a, location: firstByAsset.get(a.id) ?? null }));
}

