export interface Institution {
  id: string;
  category: string;
  legal_name: string;
  short_name: string | null;
  regulator: string;
  active: number;
  source: string;
  has_verified_pack?: boolean;
}

/** Searchable institution selector: matches legal name, short name, or any alias,
 *  filtered by category, active only. Values are stable institution ids. */
export async function searchInstitutions(
  category: string | null,
  query: string | undefined,
  limit = 25,
): Promise<Institution[]> {
  const like = query && query.trim() ? `%${normJur(query)}%` : null;
  const rows = await sql()`
    SELECT DISTINCT i.id, i.category, i.legal_name, i.short_name, i.regulator, i.active, i.source
    FROM institutions i
    LEFT JOIN institution_aliases a ON a.institution_id = i.id
    WHERE i.active = 1
      AND (${category}::text IS NULL OR i.category = ${category})
      AND (
        ${like}::text IS NULL
        OR translate(lower(i.legal_name), '.-_()', '     ') LIKE ${like}
        OR translate(lower(coalesce(i.short_name, '')), '.-_()', '     ') LIKE ${like}
        OR a.alias_norm LIKE ${like}
      )
    ORDER BY i.legal_name
    LIMIT ${limit}`;
  return rows as Institution[];
}

