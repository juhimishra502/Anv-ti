/** Update an asset + its (single) location. Used by the wizard's edit action. */
export async function updateAsset(assetId: string, input: Partial<AssetInput>): Promise<void> {
  const cols: Record<string, unknown> = {
    label: input.label, institution: input.institution, institution_id: input.institution_id,
    nominee_status: input.nominee_status, holding_mode: input.holding_mode, record_type: input.record_type,
    authority: input.authority, scheme: input.scheme, details_json: input.details_json,
  };
  const sets: string[] = [];
  const values: unknown[] = [];
  for (const [k, v] of Object.entries(cols)) {
    if (v !== undefined) { values.push(v ?? null); sets.push(`${k} = $${values.length}`); }
  }
  if (sets.length) {
    values.push(assetId);
    await sql().query(`UPDATE assets SET ${sets.join(", ")} WHERE id = $${values.length}`, values);
  }
  if (input.location) {
    const l = input.location;
    const existing = await sql()`SELECT id FROM asset_locations WHERE asset_id = ${assetId} LIMIT 1`;
    if (existing.length) {
      await sql()`UPDATE asset_locations SET state_code=${l.state_code ?? null}, district=${l.district ?? null},
        municipality=${l.municipality ?? null}, tehsil_taluk=${l.tehsil_taluk ?? null},
        village_ward=${l.village_ward ?? null}, property_identifier=${l.property_identifier ?? null}
        WHERE asset_id=${assetId}`;
    } else {
      await sql()`INSERT INTO asset_locations (id, asset_id, state_code, district, municipality, tehsil_taluk, village_ward, property_identifier, created_at)
        VALUES (${newId("loc")}, ${assetId}, ${l.state_code ?? null}, ${l.district ?? null}, ${l.municipality ?? null}, ${l.tehsil_taluk ?? null}, ${l.village_ward ?? null}, ${l.property_identifier ?? null}, ${nowIso()})`;
    }
  }
}

export async function removeAsset(caseId: string, assetId: string): Promise<void> {
  await sql()`DELETE FROM assets WHERE id = ${assetId} AND case_id = ${caseId}`;
  await touchCase(caseId);
  await audit(null, caseId, "asset.removed", assetId);
}

// ---- Roadmap ----------------------------------------------------------------

type PreservedStep = Pick<
  RoadmapStep,
  "procedure_id" | "asset_id" | "service" | "user_status" | "submitted_at" | "office" | "ack_number" | "method" | "follow_up_date" | "notes"
>;

export interface CommitRoadmapInput {
  caseId: string;
  steps: GeneratedRoadmapStep[];
  questionnaireVersion: string;
  answerVersion: string;
  schemaJson: string;
  actorUserId: string | null;
  correlationId: string;
  /** Asset ids that belong to this case — used to satisfy the roadmap_steps.asset_id FK. */
  validAssetIds: Set<string>;
}

/**
 * Generate-and-save the whole roadmap in ONE database transaction: it deletes the
 * old steps, inserts the new ones, stamps the case's questionnaire+answer version,
 * records the schema version, and writes one audit row — all atomically, so a
 * partial roadmap can never be left behind. FKs and required fields are validated
 * before the write. Preserves user-set status/tracking across regeneration.
 */
export async function commitRoadmap(input: CommitRoadmapInput): Promise<void> {
  const { caseId, steps, questionnaireVersion, answerVersion, schemaJson, actorUserId, correlationId, validAssetIds } = input;
  const now = nowIso();
  const q = sql();

  // Validate every node against the schema's required fields and the asset FK BEFORE
  // opening the transaction, so a bad node fails loudly instead of half-writing.
  for (const [i, s] of steps.entries()) {
    if (!s.service || !s.title || !s.requirement || !s.engine_status || !s.completeness || s.payload == null) {
      throw new Error(`Roadmap node ${i} is missing a required field (service/title/requirement/engine_status/completeness/payload).`);
    }
    if (s.asset_id !== null && !validAssetIds.has(s.asset_id)) {
      throw new Error(`Roadmap node ${i} references asset ${s.asset_id}, which is not in case ${caseId}.`);
    }
  }

  // Preserve user-set status AND tracking across regeneration (key: procedure+asset+service).
  const prior = (await q`
    SELECT procedure_id, asset_id, service, user_status, submitted_at, office, ack_number, method, follow_up_date, notes
    FROM roadmap_steps WHERE case_id = ${caseId}`) as PreservedStep[];
  const keyOf = (p: string | null, a: string | null, s: string) => `${p}|${a}|${s}`;
  const priorMap = new Map(prior.map((r) => [keyOf(r.procedure_id, r.asset_id, r.service), r]));

  // One atomic transaction: replace steps + stamp version + record schema + audit.
  const queries = [q`DELETE FROM roadmap_steps WHERE case_id = ${caseId}`];
  steps.forEach((s, i) => {
    const p = priorMap.get(keyOf(s.procedure_id, s.asset_id, s.service));
    queries.push(q`
      INSERT INTO roadmap_steps (id, case_id, asset_id, procedure_id, service, title, requirement,
        engine_status, completeness, execution_available, derived_done, payload, user_status,
        submitted_at, office, ack_number, method, follow_up_date, notes, sort_order, created_at, updated_at)
      VALUES (${newId("stp")}, ${caseId}, ${s.asset_id}, ${s.procedure_id}, ${s.service}, ${s.title}, ${s.requirement},
        ${s.engine_status}, ${s.completeness}, ${s.execution_available}, ${s.derived_done}, ${s.payload}, ${p?.user_status ?? "not_started"},
        ${p?.submitted_at ?? null}, ${p?.office ?? null}, ${p?.ack_number ?? null}, ${p?.method ?? null}, ${p?.follow_up_date ?? null}, ${p?.notes ?? null}, ${s.sort_order ?? i}, ${now}, ${now})`);
  });
  queries.push(q`UPDATE cases SET questionnaire_version = ${questionnaireVersion}, answer_version = ${answerVersion}, updated_at = ${now} WHERE id = ${caseId}`);
  queries.push(q`INSERT INTO questionnaire_schemas (version, schema_json, created_at) VALUES (${questionnaireVersion}, ${schemaJson}, ${now}) ON CONFLICT (version) DO NOTHING`);
  queries.push(q`INSERT INTO audit_events (id, actor_user_id, case_id, action, detail, created_at)
    VALUES (${newId("aud")}, ${actorUserId}, ${caseId}, 'roadmap.regenerated', ${`${steps.length} steps; answer_version=${answerVersion}; cid=${correlationId}`}, ${now})`);

  await q.transaction(queries);
}

const TRACKING_FIELDS = ["submitted_at", "office", "ack_number", "method", "follow_up_date", "notes"] as const;

export async function setStepTracking(
  stepId: string,
  patch: Partial<Pick<RoadmapStep, (typeof TRACKING_FIELDS)[number]>>,
): Promise<void> {
  const sets: string[] = [];
  const values: unknown[] = [];
  for (const f of TRACKING_FIELDS) {
    if (f in patch) {
      values.push((patch as Record<string, unknown>)[f] ?? null);
      sets.push(`${f} = $${values.length}`);
    }
  }
  if (!sets.length) return;
  values.push(nowIso());
  sets.push(`updated_at = $${values.length}`);
  values.push(stepId);
  await sql().query(
    `UPDATE roadmap_steps SET ${sets.join(", ")} WHERE id = $${values.length}`,
    values,
  );
}

/** All steps across the user's cases that have an upcoming/overdue follow-up date. */
export async function listRemindersForUser(userId: string): Promise<Array<RoadmapStep & { case_title: string }>> {
  const rows = await sql()`
    SELECT rs.*, c.title AS case_title FROM roadmap_steps rs
    JOIN cases c ON c.id = rs.case_id
    JOIN family_members fm ON fm.family_id = c.family_id
    WHERE fm.user_id = ${userId} AND rs.follow_up_date IS NOT NULL AND rs.follow_up_date != ''
    ORDER BY rs.follow_up_date ASC`;
  return rows as Array<RoadmapStep & { case_title: string }>;
}

