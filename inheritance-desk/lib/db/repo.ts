export interface Jurisdiction {
  code: string;
  level: string;
  parent_code: string | null;
  name: string;
  name_local: string | null;
  source: string | null;
  lgd_code?: string | null;
  active?: number;
}

export async function listChildJurisdictions(parentCode: string, level: string): Promise<Jurisdiction[]> {
  const rows = await sql()`
    SELECT code, level, parent_code, name, name_local, source, lgd_code, active FROM jurisdictions
    WHERE parent_code = ${parentCode} AND level = ${level} AND active = 1 ORDER BY name`;
  return rows as Jurisdiction[];
}

const normJur = (s: string): string =>
  s.normalize("NFKC").toLowerCase().replace(/&/g, " and ").replace(/[^a-z0-9]+/g, " ").trim().replace(/\s+/g, " ");

/** Searchable dependent selector: children of `parentCode` at `level`, matched by
 *  current name OR any historical/alternate alias (e.g. "Allahabad" -> Prayagraj).
 *  A blank query returns the full child list. LGD codes are the stored keys. */
export async function searchJurisdictions(
  parentCode: string,
  level: string,
  query?: string,
): Promise<Jurisdiction[]> {
  if (!query || !query.trim()) return listChildJurisdictions(parentCode, level);
  const like = `%${normJur(query)}%`;
  const rows = await sql()`
    SELECT DISTINCT j.code, j.level, j.parent_code, j.name, j.name_local, j.source, j.lgd_code, j.active
    FROM jurisdictions j
    LEFT JOIN jurisdiction_aliases a ON a.jurisdiction_code = j.code
    WHERE j.parent_code = ${parentCode} AND j.level = ${level} AND j.active = 1
      AND (
        translate(lower(j.name), '.-_()', '     ') LIKE ${like} OR
        a.alias_norm LIKE ${like}
      )
    ORDER BY j.name`;
  return rows as Jurisdiction[];
}

/** Resolve a stored jurisdiction code to its current official display name.
 *  Case/asset records store codes; this turns a code back into a name for display. */
export async function getJurisdiction(code: string): Promise<Jurisdiction | null> {
  const rows = await sql()`
    SELECT code, level, parent_code, name, name_local, source, lgd_code, active
    FROM jurisdictions WHERE code = ${code}`;
  return (rows[0] as Jurisdiction) ?? null;
}

